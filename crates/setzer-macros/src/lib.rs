//! Compile-time half of Setzer. Every macro reads files relative to the
//! crate root (`CARGO_MANIFEST_DIR`), the one location both `rustc` and
//! rust-analyzer know, and turns them into typed Rust:
//!
//! * `site!()` in `main.rs`: the page tree under `src/www/` as module `www`.
//!   For every page folder it generates the page's text as `Content`, its
//!   sections, the collection, `PAGE`, the registration, and attaches the
//!   folder's `mod.rs` (whose `setzer::page!(…)` holds the options);
//! * `image!("src/www/images/photo.jpg", crop: (x, y, w, h), widths: [640, 1280])`;
//! * `static_dir!("static")`: files to copy to the site root.
//!
//! Problems (a missing translation key, a link to a page that does not
//! exist, an image that cannot be read) are compile errors.

mod markdown;
mod values;

use markdown::{body_parts, split_front_matter, PartSpec};
use proc_macro::TokenStream;
use proc_macro2::{Span, TokenStream as Ts};
use quote::{format_ident, quote};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use syn::parse::{Parse, ParseStream};
use syn::{bracketed, parenthesized, Ident, LitInt, LitStr, Token};
use values::{Shape, Value, Values};

type R<T> = Result<T, String>;

fn fail(r: R<Ts>) -> TokenStream {
    match r {
        Ok(ts) => ts.into(),
        Err(msg) => quote!(compile_error!(#msg);).into(),
    }
}

fn manifest_dir() -> R<PathBuf> {
    std::env::var("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .map_err(|e| e.to_string())
}

/// The site: `setzer::site!()` in `main.rs`, in place of `mod www;`.
///
/// Reads `src/www/` (the home page) and every sub-folder whose `mod.rs`
/// calls `setzer::page!` (names starting with `_` are skipped), and
/// generates `pub mod www { … }` with, per page:
///
/// * the page's text: `content.md` (+ `content.<lang>.md`), or the folder's
///   only markdown file → `struct Content`, `fn content(lang)`;
/// * one section per `faq.md` + `faq.rs` pair → `mod faq` (its own `Content`,
///   `faq.rs` attached) and `fn faq(lang) -> Html`;
/// * `DOCUMENTS` and `documents(lang)` for `page!(documents: "posts")`;
/// * `PAGE`, its registration with the site, and the folder's `mod.rs` as a
///   child module whose public items are re-exported.
#[proc_macro]
pub fn site(input: TokenStream) -> TokenStream {
    if !input.is_empty() {
        return quote!(compile_error!("setzer::site!() takes no arguments; the pages live in src/www/");).into();
    }
    fail((|| {
        let root = manifest_dir()?.join("src").join("www");
        if !root.join("mod.rs").is_file() {
            return Err(format!(
                "setzer::site!(): {} is missing; the home page lives there",
                root.join("mod.rs").display()
            ));
        }
        let body = page_module(&root)?;
        Ok(quote! {
            /// The site's pages. Generated by `setzer::site!()` from `src/www/`.
            pub mod www {
                #body
            }
        })
    })())
}

#[derive(Default)]
struct PageArgs {
    /// `None`: found by scanning the page's folder.
    subpages: Option<Vec<Ident>>,
    documents: Option<String>,
    path: Option<String>,
    feed: Option<Ident>,
}

impl Parse for PageArgs {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let mut args = PageArgs::default();
        while !input.is_empty() {
            let key: Ident = input.parse()?;
            input.parse::<Token![:]>()?;
            match key.to_string().as_str() {
                "content" => return Err(syn::Error::new(key.span(), "page! has no `content` option: the page's text is content.md, or the folder's only markdown file")),
                "documents" => args.documents = Some(input.parse::<LitStr>()?.value()),
                "path" => args.path = Some(input.parse::<LitStr>()?.value()),
                "feed" => args.feed = Some(input.parse()?),
                "subpages" => {
                    let inner;
                    bracketed!(inner in input);
                    args.subpages = Some(inner.parse_terminated(Ident::parse, Token![,])?.into_iter().collect());
                }
                other => return Err(syn::Error::new(key.span(), format!("unknown page! option `{other}`; known: subpages, documents, path, feed"))),
            }
            if !input.is_empty() {
                input.parse::<Token![,]>()?;
            }
        }
        Ok(args)
    }
}

/// Everything inside one page's module.
fn page_module(dir: &Path) -> R<Ts> {
    let file = dir.join("mod.rs");
    let source =
        std::fs::read_to_string(&file).map_err(|e| format!("reading {}: {e}", file.display()))?;
    let args = page_args(&source).map_err(|e| format!("{}: {e}", file.display()))?;
    if !source.contains("fn render") {
        return Err(format!(
            "{}: a page needs `pub fn render(c: &Content, lang: Lang) -> Html`",
            file.display()
        ));
    }

    // The page's text and its sections.
    let (main, sections) = split_texts(dir)?;
    let mut texts = Vec::new();
    let content = format_ident!("Content");
    let content_fn = format_ident!("content");
    texts.push(match &main {
        Some(stem) => content_items(dir, stem, &content, &content_fn, false)?.0,
        None => content_items(dir, "content", &content, &content_fn, true)?.0,
    });
    for stem in &sections {
        let module = Ident::new(stem, Span::call_site());
        if source.lines().any(|l| {
            l.split("//")
                .next()
                .unwrap_or("")
                .contains(&format!("mod {stem};"))
        }) {
            return Err(format!(
                "{}: remove `mod {stem};`: site!() attaches {stem}.rs as a section, with {stem}.md as its `Content`",
                file_name(&file)
            ));
        }
        let rs = dir.join(format!("{stem}.rs"));
        if !std::fs::read_to_string(&rs)
            .unwrap_or_default()
            .contains("fn render")
        {
            return Err(format!(
                "{}: a section needs `pub fn render(c: &Content, lang: Lang) -> Html`",
                file_name(&rs)
            ));
        }
        let items = content_items(dir, stem, &content, &content_fn, false)?.0;
        let path = format!("{stem}.rs");
        texts.push(quote! {
            /// The section `#stem.rs`, with `#stem.md` as its `Content`.
            // `path = "."` keeps the page's folder as this module's folder,
            // so `#path` resolves next to the page's `mod.rs`.
            #[path = "."]
            pub mod #module {
                #items
                #[path = #path]
                mod __section;
                #[allow(unused_imports)]
                pub use __section::*;
            }
            /// The section `#stem.rs`, rendered with its text in `lang`.
            pub fn #module(lang: ::setzer::Lang) -> ::setzer::Html {
                #module::render(#module::content(lang), lang)
            }
        });
    }

    let children = match &args.subpages {
        Some(list) => list.clone(),
        None => scan_pages(dir)?,
    };
    let child_modules = children
        .iter()
        .map(|c| {
            let body = page_module(&dir.join(c.to_string()))?;
            Ok(quote!(pub mod #c { #body }))
        })
        .collect::<R<Vec<Ts>>>()?;

    let path = match &args.path {
        Some(p) => quote!(Some(#p)),
        None => quote!(None),
    };
    let feed = match &args.feed {
        Some(f) => quote!(Some(#f)),
        None => quote!(None),
    };
    let (documents, render) = match &args.documents {
        Some(d) => (
            documents_items(&dir.join(d))?,
            quote! {
                ::setzer::RenderFn::Each(DOCUMENTS, {
                    fn __setzer_render(doc: &'static ::setzer::Document, lang: ::setzer::Lang) -> ::setzer::Html { render(doc.doc(lang), content(lang), lang) }
                    __setzer_render
                })
            },
        ),
        None => (
            quote!(),
            quote! {
                ::setzer::RenderFn::Single({
                    fn __setzer_render(lang: ::setzer::Lang) -> ::setzer::Html { render(content(lang), lang) }
                    __setzer_render
                })
            },
        ),
    };

    Ok(quote! {
        #(#texts)*
        #documents

        // The folder's own code; `setzer::page!` in it imports this module.
        #[path = "mod.rs"]
        mod __page;
        #[allow(unused_imports)]
        pub use __page::*;

        /// This page. Link to it with `setzer::href(&PAGE, lang)`.
        pub static PAGE: ::setzer::PageDef = ::setzer::PageDef {
            module: module_path!(),
            path: #path,
            render: #render,
            meta: {
                fn __setzer_meta(lang: ::setzer::Lang) -> ::setzer::Meta {
                    let c = content(lang);
                    ::setzer::Meta { title: ::setzer::ContentMeta::title(c), description: ::setzer::ContentMeta::description(c) }
                }
                __setzer_meta
            },
            feed: #feed,
        };

        #[::setzer::__linkme::distributed_slice(::setzer::PAGES)]
        #[linkme(crate = ::setzer::__linkme)]
        static __SETZER_REGISTER: &::setzer::PageDef = &PAGE;

        #(#child_modules)*
    })
}

/// File stems of the markdown files directly in `dir`, language suffix
/// removed: `content.md`, `content.de.md`, `faq.md` → `content`, `faq`.
fn text_stems(dir: &Path) -> Vec<String> {
    let mut stems: Vec<String> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            let stem = name.strip_suffix(".md")?.to_string();
            Some(match stem.rsplit_once('.') {
                Some((base, lang)) if lang_variant(lang).is_ok() => base.to_string(),
                _ => stem,
            })
        })
        .collect();
    stems.sort();
    stems.dedup();
    stems
}

/// Splits the markdown files directly in `dir` into the page's text and its
/// sections. A file with a same-named `.rs` file is a section. Of the rest,
/// `content.md` is the page's text, or the only file if there is just one;
/// any other leftover is an error, so no text is silently unused.
fn split_texts(dir: &Path) -> R<(Option<String>, Vec<String>)> {
    let (sections, rest): (Vec<String>, Vec<String>) = text_stems(dir)
        .into_iter()
        .partition(|s| s != "content" && dir.join(format!("{s}.rs")).is_file());
    for stem in &sections {
        if syn::parse_str::<Ident>(stem).is_err() {
            return Err(format!(
                "{}: `{stem}` is not a valid module name for a section",
                file_name(&dir.join(format!("{stem}.md")))
            ));
        }
    }
    let main = match rest.as_slice() {
        [] => None,
        [one] => Some(one.clone()),
        _ if rest.iter().any(|s| s == "content") => {
            let other = rest.iter().find(|s| *s != "content").unwrap();
            return Err(format!(
                "{}: content.md is this page's text; for {other}.md add {other}.rs with `pub fn render(c: &Content, lang: Lang) -> Html` (a section)",
                file_name(&dir.join(format!("{other}.md")))
            ));
        }
        _ => {
            return Err(format!(
                "{}: several markdown files ({}); name the page's text content.md and give every other file a same-named .rs file (a section)",
                file_name(dir),
                rest.iter().map(|s| format!("{s}.md")).collect::<Vec<_>>().join(", ")
            ));
        }
    };
    Ok((main, sections))
}

/// The options inside the first `page!(…)` call of a source file.
fn page_args(source: &str) -> R<PageArgs> {
    for (i, _) in source.match_indices("page!") {
        let line_start = source[..i].rfind('\n').map_or(0, |p| p + 1);
        if source[line_start..i].contains("//")
            || source[..i]
                .chars()
                .next_back()
                .is_some_and(|c| c.is_alphanumeric() || c == '_')
        {
            continue;
        }
        let rest = source[i + 5..].trim_start();
        let Some(open) = rest.chars().next() else {
            continue;
        };
        let close = match open {
            '(' => ')',
            '{' => '}',
            '[' => ']',
            _ => continue,
        };
        let (mut depth, mut in_str, mut prev, mut end) = (0, false, ' ', None);
        for (j, c) in rest.char_indices() {
            if in_str {
                in_str = !(c == '"' && prev != '\\');
            } else if c == '"' {
                in_str = true;
            } else if c == open {
                depth += 1;
            } else if c == close {
                depth -= 1;
                if depth == 0 {
                    end = Some(j);
                    break;
                }
            }
            prev = c;
        }
        let inner = &rest[1..end.ok_or("unclosed page!( … )")?];
        return syn::parse_str::<PageArgs>(inner).map_err(|e| format!("page! options: {e}"));
    }
    Err("no `setzer::page!(…)` call".into())
}

/// Sub-folders of `dir` whose `mod.rs` calls `page!`. Names starting with
/// `_` or `.` are skipped, so `_draft/` is left out. Sorted by name.
fn scan_pages(dir: &Path) -> R<Vec<Ident>> {
    let mut names: Vec<String> = Vec::new();
    for entry in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        if name.starts_with('_') || name.starts_with('.') || !path.is_dir() {
            continue;
        }
        if calls_page(&path.join("mod.rs")) {
            names.push(name);
        }
    }
    names.sort();
    names
        .into_iter()
        .map(|n| {
            syn::parse_str::<Ident>(&n).map_err(|_| {
                format!(
                    "{}: `{n}` is not a valid module name for a page",
                    dir.display()
                )
            })
        })
        .collect()
}

/// Whether a source file calls `page!` (outside `//` comments).
fn calls_page(file: &Path) -> bool {
    let Ok(text) = std::fs::read_to_string(file) else {
        return false;
    };
    text.lines()
        .map(|l| l.split("//").next().unwrap_or(""))
        .any(|line| {
            line.match_indices("page!").any(|(i, _)| {
                let before = line[..i].chars().next_back();
                let after = line[i + 5..].trim_start().chars().next();
                !before.is_some_and(|c| c.is_alphanumeric() || c == '_')
                    && matches!(after, Some('(' | '{' | '['))
            })
        })
}

/// Struct, one static per language file, and the language lookup.
fn content_items(
    folder: &Path,
    stem: &str,
    ty: &Ident,
    func: &Ident,
    optional: bool,
) -> R<(Ts, Shape)> {
    let mut files: Vec<(Option<String>, PathBuf)> = Vec::new();
    if let Ok(dir) = std::fs::read_dir(folder) {
        for entry in dir.flatten() {
            let path = entry.path();
            let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
                continue;
            };
            if name == format!("{stem}.md") {
                files.push((None, path));
            } else if let Some(lang) = name
                .strip_prefix(&format!("{stem}."))
                .and_then(|r| r.strip_suffix(".md"))
            {
                files.push((Some(lang.to_string()), path));
            }
        }
    }
    files.sort();
    let prefix = stem.to_uppercase().replace('-', "_");
    if files.is_empty() {
        if !optional {
            return Err(format!(
                "no {stem}.md (or {stem}.<lang>.md) in {}",
                folder.display()
            ));
        }
        // A page without text: only an empty body.
        let name = format_ident!("{prefix}_DEFAULT");
        return Ok((
            quote! {
                pub struct #ty { pub body: ::setzer::Body }
                pub static #name: #ty = #ty { body: ::setzer::Body::EMPTY };
                pub fn #func(_lang: ::setzer::Lang) -> &'static #ty { &#name }
                impl ::setzer::ContentMeta for #ty {
                    fn title(&self) -> Option<&'static str> { None }
                    fn description(&self) -> Option<&'static str> { None }
                }
            },
            Shape::Table(BTreeMap::from([("body".to_string(), Shape::Body)])),
        ));
    }
    if files[0].0.is_some() {
        return Err(format!(
            "{}: has language files but no {stem}.md fallback",
            folder.display()
        ));
    }

    let manifest = manifest_dir()?;
    let mut parsed: Vec<(Option<String>, Shape, Values)> = Vec::new();
    for (lang, path) in &files {
        let text = std::fs::read_to_string(path)
            .map_err(|e| format!("reading {}: {e}", path.display()))?;
        let (fm, body) =
            split_front_matter(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        let table: toml::Table =
            toml::from_str(fm).map_err(|e| format!("{}: front matter: {e}", path.display()))?;
        if table.contains_key("body") {
            return Err(format!(
                "{}: `body` is reserved for the markdown below the front matter",
                path.display()
            ));
        }
        let mut values =
            values::from_table(&table).map_err(|e| format!("{}: {e}", path.display()))?;
        values.insert(
            "body".into(),
            Value::Body(
                body_parts(body, &manifest).map_err(|e| format!("{}: {e}", path.display()))?,
            ),
        );
        let shape = Shape::of(&values).map_err(|e| format!("{}: {e}", path.display()))?;
        parsed.push((lang.clone(), shape, values));
    }
    let reference = file_name(&files[0].1);
    for ((_, other, _), (_, path)) in parsed[1..].iter().zip(&files[1..]) {
        if let Some(problem) = values::diff(&parsed[0].1, other, "") {
            return Err(format!(
                "{} {problem} (compared with {reference})",
                file_name(path)
            ));
        }
    }

    let mut structs = Vec::new();
    values::emit_struct(ty, &parsed[0].1, &mut structs);
    let mut statics = Vec::new();
    let mut arms = Vec::new();
    for (lang, _, values) in &parsed {
        let name = format_ident!(
            "{prefix}_{}",
            lang.as_deref().unwrap_or("default").to_uppercase()
        );
        let literal = values::emit_value(ty, &Value::Table(values.clone()));
        statics.push(quote!(pub static #name: #ty = #literal;));
        if let Some(l) = lang {
            let variant = lang_variant(l)?;
            arms.push(quote!(#variant => &#name,));
        }
    }
    // Swiss German without its own file reads the German one.
    let has_lang = |code: &str| parsed.iter().any(|(l, _, _)| l.as_deref() == Some(code));
    if has_lang("de") && !has_lang("gsw") {
        let de = format_ident!("{prefix}_DE");
        arms.push(quote!(::setzer::Lang::Gsw => &#de,));
    }
    let default = format_ident!("{prefix}_DEFAULT");
    let includes = files.iter().map(|(_, p)| include(p));
    let has =
        |k: &str| matches!(&parsed[0].1, Shape::Table(f) if matches!(f.get(k), Some(Shape::Str)));
    let title = if has("title") {
        quote!(Some(self.title))
    } else {
        quote!(None)
    };
    let description = if has("description") {
        quote!(Some(self.description))
    } else {
        quote!(None)
    };
    Ok((
        quote! {
            #(#includes)*
            #(#structs)*
            #(#statics)*
            impl ::setzer::ContentMeta for #ty {
                fn title(&self) -> Option<&'static str> { #title }
                fn description(&self) -> Option<&'static str> { #description }
            }
            /// Text in `lang`: the `<lang>` file if present, else the file without suffix.
            #[allow(unreachable_patterns)]
            pub fn #func(lang: ::setzer::Lang) -> &'static #ty {
                match lang {
                    #(#arms)*
                    _ => &#default,
                }
            }
        },
        parsed.into_iter().next().unwrap().1,
    ))
}

fn include(path: &Path) -> Ts {
    let p = path.to_string_lossy().to_string();
    quote!(
        const _: &[u8] = include_bytes!(#p);
    )
}

/// Path below the crate root, for messages: `src/www/blog/content.de.md`.
fn file_name(p: &Path) -> String {
    let rel = manifest_dir()
        .ok()
        .and_then(|m| p.strip_prefix(m).ok().map(Path::to_path_buf));
    rel.unwrap_or_else(|| p.to_path_buf())
        .to_string_lossy()
        .to_string()
}

fn lang_variant(code: &str) -> R<Ts> {
    Ok(match code {
        "en" => quote!(::setzer::Lang::En),
        "de" => quote!(::setzer::Lang::De),
        "fr" => quote!(::setzer::Lang::Fr),
        "it" => quote!(::setzer::Lang::It),
        "gsw" => quote!(::setzer::Lang::Gsw),
        other => {
            return Err(format!(
                "unknown language suffix .{other}.md (known: en, de, fr, it, gsw)"
            ))
        }
    })
}

// ---- documents (collections) ---------------------------------------------------

struct DocSpec {
    lang: Option<String>,
    title: String,
    date: Option<String>,
    description: Option<String>,
    body: Vec<PartSpec>,
}

fn documents_items(dir: &Path) -> R<Ts> {
    let manifest = manifest_dir()?;
    let mut by_slug: BTreeMap<String, Vec<DocSpec>> = BTreeMap::new();
    let mut includes = Vec::new();
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
        .map_err(|e| format!("documents: reading {}: {e}", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "md"))
        .collect();
    entries.sort();
    for path in entries {
        includes.push(include(&path));
        let stem = path.file_stem().unwrap().to_string_lossy().to_string();
        let (base, lang) = match stem.rsplit_once('.') {
            Some((b, l)) if lang_variant(l).is_ok() => (b.to_string(), Some(l.to_string())),
            _ => (stem.clone(), None),
        };
        let (slug, file_date) = if base.len() > 11
            && base.as_bytes()[10] == b'-'
            && base[..10].chars().filter(|c| *c == '-').count() == 2
        {
            (base[11..].to_string(), Some(base[..10].to_string()))
        } else {
            (base.clone(), None)
        };
        let text = std::fs::read_to_string(&path)
            .map_err(|e| format!("reading {}: {e}", path.display()))?;
        let (fm, body) =
            split_front_matter(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        let table: toml::Table =
            toml::from_str(fm).map_err(|e| format!("{}: front matter: {e}", path.display()))?;
        let title = table
            .get("title")
            .and_then(|v| v.as_str())
            .ok_or(format!("{}: front matter needs `title`", path.display()))?
            .to_string();
        let date = table
            .get("date")
            .map(|d| {
                d.as_str()
                    .map(str::to_string)
                    .unwrap_or_else(|| d.to_string())
            })
            .or(file_date);
        let description = table
            .get("description")
            .and_then(|v| v.as_str())
            .map(str::to_string);
        let body = body_parts(body, &manifest).map_err(|e| format!("{}: {e}", path.display()))?;
        by_slug.entry(slug).or_default().push(DocSpec {
            lang,
            title,
            date,
            description,
            body,
        });
    }
    let mut docs: Vec<(String, Vec<DocSpec>)> = by_slug.into_iter().collect();
    let newest = |v: &Vec<DocSpec>| v.iter().filter_map(|d| d.date.clone()).max();
    docs.sort_by(|a, b| newest(&b.1).cmp(&newest(&a.1)).then_with(|| a.0.cmp(&b.0)));

    let documents = docs.iter().map(|(slug, versions)| {
        let versions = versions.iter().map(|d| {
            let lang = match &d.lang {
                Some(l) => {
                    let v = lang_variant(l).unwrap();
                    quote!(Some(#v))
                }
                None => quote!(None),
            };
            let title = &d.title;
            let date = opt_str(&d.date);
            let description = opt_str(&d.description);
            let body = markdown::emit_parts(&d.body);
            quote!((#lang, ::setzer::Doc::__new(#title, #date, #description, #body, #slug, #lang, &PAGE)))
        });
        quote!(::setzer::Document { slug: #slug, versions: &[#(#versions),*] })
    });
    Ok(quote! {
        #(#includes)*
        /// The collection, newest first: every document with all its languages.
        pub static DOCUMENTS: &[::setzer::Document] = &[#(#documents),*];

        /// The documents that exist in `lang`, newest first.
        pub fn documents(lang: ::setzer::Lang) -> impl Iterator<Item = &'static ::setzer::Doc> {
            ::setzer::documents_in(DOCUMENTS, lang)
        }
    })
}

fn opt_str(s: &Option<String>) -> Ts {
    match s {
        Some(s) => quote!(Some(#s)),
        None => quote!(None),
    }
}

// ---- image! --------------------------------------------------------------------

struct ImageArgs {
    file: LitStr,
    crop: Option<(u32, u32, u32, u32)>,
    widths: Vec<u32>,
}

impl Parse for ImageArgs {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let file: LitStr = input.parse()?;
        let mut crop = None;
        let mut widths = Vec::new();
        while !input.is_empty() {
            input.parse::<Token![,]>()?;
            if input.is_empty() {
                break;
            }
            let key: Ident = input.parse()?;
            input.parse::<Token![:]>()?;
            match key.to_string().as_str() {
                "crop" => {
                    let inner;
                    parenthesized!(inner in input);
                    let n: Vec<u32> = inner
                        .parse_terminated(LitInt::parse, Token![,])?
                        .iter()
                        .map(|l| l.base10_parse())
                        .collect::<syn::Result<_>>()?;
                    if n.len() != 4 {
                        return Err(syn::Error::new(key.span(), "crop: (x, y, width, height)"));
                    }
                    crop = Some((n[0], n[1], n[2], n[3]));
                }
                "widths" => {
                    let inner;
                    bracketed!(inner in input);
                    widths = inner
                        .parse_terminated(LitInt::parse, Token![,])?
                        .iter()
                        .map(|l| l.base10_parse())
                        .collect::<syn::Result<_>>()?;
                }
                other => {
                    return Err(syn::Error::new(
                        key.span(),
                        format!("unknown image! key `{other}`; known: crop, widths"),
                    ))
                }
            }
        }
        if widths.is_empty() {
            return Err(syn::Error::new(file.span(), "image! needs `widths: [...]`"));
        }
        Ok(ImageArgs { file, crop, widths })
    }
}

/// An image file (path relative to the crate root, e.g.
/// `"src/www/images/photo.jpg"`), embedded in the program and resized to
/// `widths` when the site is written, if a page uses it.
#[proc_macro]
pub fn image(input: TokenStream) -> TokenStream {
    let args = match syn::parse::<ImageArgs>(input) {
        Ok(a) => a,
        Err(e) => return e.to_compile_error().into(),
    };
    fail(image_impl(args))
}

fn image_impl(args: ImageArgs) -> R<Ts> {
    use sha2::{Digest, Sha256};
    let path = manifest_dir()?.join(args.file.value());
    let (w, h) = image_dims::image_dimensions(&path)
        .map_err(|e| format!("image!: {}: {e}", path.display()))?;
    let (cw, ch) = match args.crop {
        Some((x, y, cw, ch)) => {
            if x + cw > w || y + ch > h {
                return Err(format!(
                    "image!: crop ({x}, {y}, {cw}, {ch}) exceeds the {w}×{h} image {}",
                    path.display()
                ));
            }
            (cw, ch)
        }
        None => (w, h),
    };
    let mut widths: Vec<u32> = args.widths.iter().copied().filter(|&x| x <= cw).collect();
    widths.sort_unstable();
    widths.dedup();
    if widths.is_empty() {
        return Err(format!(
            "image!: every width is larger than the {cw}px wide image"
        ));
    }
    // Stable across machines: hash the path below the crate and the crop.
    let rel = path
        .strip_prefix(manifest_dir()?)
        .unwrap_or(&path)
        .to_string_lossy()
        .to_string();
    let digest = Sha256::digest(format!("{rel}{:?}", args.crop).as_bytes());
    let stem = path.file_stem().unwrap().to_string_lossy();
    let name = format!(
        "{stem}-{}",
        digest
            .iter()
            .take(4)
            .map(|b| format!("{b:02x}"))
            .collect::<String>()
    );
    let max = *widths.last().unwrap();
    let height = ((max as f64) * (ch as f64) / (cw as f64)).round() as u32;
    let src = format!("/img/{name}-{max}.jpg");
    let srcset = widths
        .iter()
        .map(|w| format!("/img/{name}-{w}.jpg {w}w"))
        .collect::<Vec<_>>()
        .join(", ");
    let abs = path.to_string_lossy().to_string();
    let crop = match args.crop {
        Some((x, y, cw, ch)) => quote!(Some((#x, #y, #cw, #ch))),
        None => quote!(None),
    };
    Ok(
        quote!(::setzer::ImageRef::__new(include_bytes!(#abs), #name, #crop, &[#(#widths),*], #max, #height, #src, #srcset)),
    )
}

// ---- static_dir! ---------------------------------------------------------------

/// Every file below a folder of the crate (path relative to `Cargo.toml`),
/// embedded in the program and copied to the site root when it is written.
#[proc_macro]
pub fn static_dir(input: TokenStream) -> TokenStream {
    let dir = match syn::parse::<LitStr>(input) {
        Ok(l) => l.value(),
        Err(e) => return e.to_compile_error().into(),
    };
    fail((|| {
        let root = manifest_dir()?.join(&dir);
        let mut files = Vec::new();
        for entry in walkdir::WalkDir::new(&root).sort_by_file_name() {
            let entry = entry.map_err(|e| format!("static_dir!: {e}"))?;
            if !entry.file_type().is_file() || entry.file_name() == ".DS_Store" {
                continue;
            }
            let rel = entry
                .path()
                .strip_prefix(&root)
                .unwrap()
                .components()
                .map(|c| c.as_os_str().to_string_lossy().to_string())
                .collect::<Vec<_>>()
                .join("/");
            let abs = entry.path().to_string_lossy().to_string();
            files.push(quote!(::setzer::StaticFile { path: #rel, bytes: include_bytes!(#abs) }));
        }
        Ok(quote!(&[#(#files),*]))
    })())
}
